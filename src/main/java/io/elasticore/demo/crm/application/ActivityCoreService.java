    /**
     * Returns every Activity as ActivityDTO.
     */
    public List<ActivityDTO> findAll() {
        accessAll("read");
        return query.findAll().stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Returns every Activity as ActivityDTO, sorted.
     */
    public List<ActivityDTO> findAll(Sort sort) {
        accessAll("read");
        return query.findAll(sort).stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Deletes Activity entities matching the search criteria.
     *
     * Each one is loaded and removed rather than deleted in bulk, so its
     * members go with it and every listener that guards a row still runs.
     */
    @Transactional
    public long delete(ActivitySrchDTO searchDTO) {
        accessAll("delete");
        Specification<Activity> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        List<Activity> found = query.findAll(specification);
        for (Activity each : found) {
            repository.delete(each);
        }
        return found.size();
    }

    /**
     * Finds Activity entities matching the search criteria, unpaged.
     */
    public List<ActivityDTO> listBySearch(ActivitySrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<Activity> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        Sort sort = searchDTO.getSort();
        List<Activity> result = (sort == null)
                ? query.findAll(specification)
                : query.findAll(specification, sort);
        return result.stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Finds Activity entities matching the search criteria, paged.
     */
    public Page<ActivityDTO> findBySearch(ActivitySrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<Activity> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        Pageable pageable = searchDTO.getPageable();
        return query.findAll(specification, pageable)
                .map(CrmMapper::toDTO);
    }

    /**
     * Finds the first Activity matching the search criteria, or null.
     */
    public ActivityDTO findFirstBySearch(ActivitySrchDTO searchDTO) {
        searchDTO.setPageSize(1);
        List<ActivityDTO> list = findBySearch(searchDTO).getContent();
        return list.isEmpty() ? null : list.get(0);
    }

    /**
     * Counts Activity entities matching the search criteria.
     */
    public long countBySearch(ActivitySrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<Activity> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        return query.count(specification);
    }

    /**
     * Finds a Activity by its identifier.
     */
    public Optional<ActivityDTO> findById(Long activityId) {
        return repository.findById(activityId)
                .filter(this::readable)
                .map(e -> CrmMapper.toDTO(e, MappingContext.withGuard(2)));
    }

    /**
     * Saves a new Activity from the given DTO.
     *
     * Creates only. An identifier that is already taken is refused rather
     * than merged over, so a create request can never overwrite a row.
     */
    @Transactional
    public ActivityDTO save(ActivityDTO dto) {
        BeanValidation.validate(dto);
        accessCreate(dto);
        if (dto.getActivityId() != null && repository.existsById(dto.getActivityId()))
            throw new DuplicateKeyException("Activity " + dto.getActivityId() + " already exists; update it instead");
        Activity entity = CrmMapper.toEntity(dto, entityManager);
        entity.setActivityId(null);
        entity.requireReferences(entityManager::find);
        beforeSave(entity, dto);
        Activity result = readBack(repository.save(entity));
        return CrmMapper.toDTO(result);
    }

    /**
     * Called with each Activity a request has just written, before it
     * is saved - on create, update, batch update and update by condition.
     *
     * Empty here. Override it in the extension service to let the aggregate
     * finish what the request started: recompute a total, stamp a state.
     */
    protected void beforeSave(Activity entity) {
    }

    /**
     * The same moment, with the request that wrote it - for what the entity
     * cannot tell by itself: whether this request carried a value, which a
     * password to be hashed needs to know on every one of the four paths.
     *
     * Calls beforeSave(entity) here; override either one.
     */
    protected void beforeSave(Activity entity, ActivityDTO request) {
        beforeSave(entity);
    }

    /**
     * Updates an existing Activity from the given DTO.
     */
    @Transactional
    public ActivityDTO update(ActivityDTO dto) {
        BeanValidation.validatePresent(dto);
        Activity entity = repository.findById(dto.getActivityId()).orElse(null);
        accessUpdate(entity, dto);
        if (entity == null)
            throw new EntityNotFoundException("Invalid ActivityDTO ID");
        CrmMapper.mapping(dto, entity, true, entityManager);
        entity.requireReferences(entityManager::find);
        beforeSave(entity, dto);
        return CrmMapper.toDTO(readBack(repository.save(entity)));
    }

    /**
     * Updates multiple Activity entities in one transaction, each
     * through update(dto) - so an override of update() in the extension
     * service governs PUT /batch too.
     */
    @Transactional
    public void batchUpdate(List<ActivityDTO> dtoList) {
        if (dtoList == null || dtoList.isEmpty()) {
            return;
        }
        for (ActivityDTO dto : dtoList) {
            update(dto);
        }
    }

    /**
     * Deletes Activity entities by their key DTOs.
     */
    @Transactional
    public List<Boolean> delete(List<ActivityKeyDTO> dtoList) {
        List<Boolean> result = new ArrayList<>();
        for (ActivityKeyDTO dto : dtoList) {
            result.add(this.deleteById(dto.getActivityId()));
        }
        return result;
    }

    /**
     * Deletes a Activity by its identifier.
     */
    @Transactional
    public boolean deleteById(Long activityId) {
        repository.findById(activityId).ifPresent(e -> accessWrite(e, "delete"));
        repository.findById(activityId).ifPresent(repository::delete);
        return !repository.existsById(activityId);
    }

    /**
     * Updates Activity entities matching the search criteria,
     * using non-null fields from the update DTO.
     */
    @Transactional
    public int updateBySpecification(ActivityDTO dto, ActivitySrchDTO srchDTO) {
        return updateBySpecification(dto, CrmMapper.toSpec(srchDTO));
    }

    /**
     * Applies the non-null fields of the DTO to every Activity the
     * Specification matches. Requires at least one condition so a whole
     * table can never be updated by accident.
     *
     * Each row is loaded and changed through the mapper rather than by a bulk
     * UPDATE, so the version, the audit trail and every rule the entity
     * checks on write still apply to it.
     */
    @Transactional
    public int updateBySpecification(ActivityDTO dto, Specification<Activity> spec) {
        EntityManager em = entityManager;
        CriteriaBuilder cb = em.getCriteriaBuilder();
        CriteriaQuery<Activity> probe = cb.createQuery(Activity.class);
        Predicate predicate = spec == null ? null : spec.toPredicate(probe.from(Activity.class), probe, cb);
        if (predicate == null)
            throw new IllegalArgumentException("Update condition is missing. Full table update is not allowed.");
        if (dto.getActivityId() != null)
            throw new IllegalArgumentException("An update by condition cannot change an identifier; use update(dto) for one row.");
        BeanValidation.validatePresent(dto);
        accessUpdateAll(dto);

        List<Activity> targets = query.findAll(spec);
        for (Activity entity : targets) {
            CrmMapper.mapping(dto, entity, true, em);
            entity.requireReferences(entityManager::find);
            beforeSave(entity, dto);
            repository.save(entity);
        }
        return targets.size();
    }

    /** Read back after a save: the reference by id is joined read-only, and the reply shows what it points at. */
    private Activity readBack(Activity saved) {
        try {
            entityManager.flush();
        } catch (RuntimeException ex) {
            // As the commit would have said it: a duplicate key is a 409, not a 500.
            RuntimeException translated = new org.springframework.orm.jpa.vendor.HibernateJpaDialect().translateExceptionIfPossible(ex);
            throw translated != null ? translated : ex;
        }
        entityManager.refresh(saved);
        return saved;
    }

    /** @access of the DSL. */
    protected static final io.elasticore.springboot3.security.AccessPolicy ACCESS =
            io.elasticore.springboot3.security.AccessPolicy.parse("Activity", "create=REP, delete=REP&owner, read=REP&owner, update=REP&owner", "ADMIN");

    /** Who is asking: a visitor unless signed in, the application itself inside CurrentUser.runAsSystem. */
    protected io.elasticore.springboot3.security.CurrentUser currentUser = new io.elasticore.springboot3.security.SessionCurrentUser();

    /** The application's CurrentUser bean, when it has one - Spring Security's, say. */
