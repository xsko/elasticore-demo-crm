    /** A search narrowed to the caller's own rows where read is the owner's: an equality, whatever the field searches by. */
    private Specification<Contact> ownedOnly(Specification<Contact> spec) {
        Object owner = ACCESS.ownerFilter(currentUser, "read");
        if (owner == null) return spec;
        final Long id = io.elasticore.springboot3.security.AccessPolicy.as(owner, Long.class);
        Specification<Contact> mine = (r, q, cb) -> cb.equal(r.get("ownerMemberId"), id);
        return spec == null ? mine : spec.and(mine);
    }

    private boolean readable(Contact entity) {
        ACCESS.require(currentUser, "read");
        return ACCESS.owns(currentUser, "read", entity.getOwnerMemberId());
    }

    private void accessWrite(Contact entity, String operation) {
        ACCESS.require(currentUser, operation);
        if (!ACCESS.owns(currentUser, operation, entity.getOwnerMemberId()))
            throw new EntityNotFoundException("Contact not found");
    }

    private void accessCreate(ContactDTO dto) {
        ACCESS.require(currentUser, "create");
        // Whoever is signed in owns what they create - a visitor's claim is cleared, not kept.
        if (!ACCESS.isAdmin(currentUser)) dto.setOwnerMemberId(io.elasticore.springboot3.security.AccessPolicy.as(currentUser.id(), Long.class));
        hashPasswords(dto);
    }

    private void accessUpdate(Contact entity, ContactDTO dto) {
        if (entity == null) return;
        accessWrite(entity, "update");
        if (!ACCESS.isAdmin(currentUser)) {
            dto.setOwnerMemberId(entity.getOwnerMemberId());
        }
        hashPasswords(dto);
    }

    private void accessUpdateAll(ContactDTO dto) {
        accessAll("update");
        if (!ACCESS.isAdmin(currentUser)) {
            dto.setOwnerMemberId(null);
        }
        hashPasswords(dto);
    }

