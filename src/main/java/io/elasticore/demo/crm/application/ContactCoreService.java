    protected void beforeSave(Contact entity, ContactDTO request) {
        beforeSave(entity);
    }

    /**
     * Updates an existing Contact from the given DTO.
     */
    @Transactional
    public ContactDTO update(ContactDTO dto) {
        BeanValidation.validatePresent(dto);
        Contact entity = repository.findById(dto.getContactId()).orElse(null);
        accessUpdate(entity, dto);
        if (entity == null)
            throw new EntityNotFoundException("Invalid ContactDTO ID");
        // A masked field sent back as the response showed it keeps the stored value.
        if (entity.getEmail() != null && io.elasticore.springboot3.mask.MaskType.EMAIL.apply(entity.getEmail()).equals(dto.getEmail())) dto.setEmail(entity.getEmail());
        if (entity.getPhone() != null && io.elasticore.springboot3.mask.MaskType.PHONE.apply(entity.getPhone()).equals(dto.getPhone())) dto.setPhone(entity.getPhone());
        CrmMapper.mapping(dto, entity, true, entityManager);
        entity.requireReferences(entityManager::find);
        beforeSave(entity, dto);
        return CrmMapper.toDTO(readBack(repository.save(entity)));
    }

    /**
     * Updates multiple Contact entities in one transaction, each
     * through update(dto) - so an override of update() in the extension
     * service governs PUT /batch too.
     */
    @Transactional
    public void batchUpdate(List<ContactDTO> dtoList) {
        if (dtoList == null || dtoList.isEmpty()) {
            return;
        }
        for (ContactDTO dto : dtoList) {
            update(dto);
        }
    }

    /**
     * Deletes Contact entities by their key DTOs.
     */
    @Transactional
    public List<Boolean> delete(List<ContactKeyDTO> dtoList) {
        List<Boolean> result = new ArrayList<>();
        for (ContactKeyDTO dto : dtoList) {
            result.add(this.deleteById(dto.getContactId()));
        }
        return result;
    }

    /**
     * Deletes a Contact by its identifier.
     */
    @Transactional
    public boolean deleteById(Long contactId) {
        repository.findById(contactId).ifPresent(e -> accessWrite(e, "delete"));
        repository.findById(contactId).ifPresent(repository::delete);
        return !repository.existsById(contactId);
    }

    /**
     * Updates Contact entities matching the search criteria,
     * using non-null fields from the update DTO.
     */
    @Transactional
    public int updateBySpecification(ContactDTO dto, ContactSrchDTO srchDTO) {
        return updateBySpecification(dto, CrmMapper.toSpec(srchDTO));
    }

    /**
     * Applies the non-null fields of the DTO to every Contact the
     * Specification matches. Requires at least one condition so a whole
     * table can never be updated by accident.
     *
     * Each row is loaded and changed through the mapper rather than by a bulk
     * UPDATE, so the version, the audit trail and every rule the entity
     * checks on write still apply to it.
     */
    @Transactional
    public int updateBySpecification(ContactDTO dto, Specification<Contact> spec) {
        EntityManager em = entityManager;
        CriteriaBuilder cb = em.getCriteriaBuilder();
        CriteriaQuery<Contact> probe = cb.createQuery(Contact.class);
        Predicate predicate = spec == null ? null : spec.toPredicate(probe.from(Contact.class), probe, cb);
        if (predicate == null)
            throw new IllegalArgumentException("Update condition is missing. Full table update is not allowed.");
        if (dto.getContactId() != null)
            throw new IllegalArgumentException("An update by condition cannot change an identifier; use update(dto) for one row.");
        BeanValidation.validatePresent(dto);
        accessUpdateAll(dto);

        List<Contact> targets = query.findAll(spec);
        for (Contact entity : targets) {
            CrmMapper.mapping(dto, entity, true, em);
            entity.requireReferences(entityManager::find);
            beforeSave(entity, dto);
            repository.save(entity);
        }
        return targets.size();
    }

    /** Read back after a save: the reference by id is joined read-only, and the reply shows what it points at. */
    private Contact readBack(Contact saved) {
        try {
            entityManager.flush();
        } catch (RuntimeException ex) {
            // As the commit would have said it: a duplicate key is a 409, not a 500.
            RuntimeException translated = new org.springframework.orm.jpa.vendor.HibernateJpaDialect().translateExceptionIfPossible(ex);
            throw translated != null ? translated : ex;
        }
        entityManager.refresh(saved);
        return saved;
    }

