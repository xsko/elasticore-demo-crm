    /**
     * Returns every KnowledgeArticle as KnowledgeArticleDTO.
     */
    public List<KnowledgeArticleDTO> findAll() {
        accessAll("read");
        return query.findAll().stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Returns every KnowledgeArticle as KnowledgeArticleDTO, sorted.
     */
    public List<KnowledgeArticleDTO> findAll(Sort sort) {
        accessAll("read");
        return query.findAll(sort).stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Deletes KnowledgeArticle entities matching the search criteria.
     *
     * Each one is loaded and removed rather than deleted in bulk, so its
     * members go with it and every listener that guards a row still runs.
     */
    @Transactional
    public long delete(KnowledgeArticleSrchDTO searchDTO) {
        accessAll("delete");
        Specification<KnowledgeArticle> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        List<KnowledgeArticle> found = query.findAll(specification);
        for (KnowledgeArticle each : found) {
            repository.delete(each);
        }
        return found.size();
    }

    /**
     * Finds KnowledgeArticle entities matching the search criteria, unpaged.
     */
    public List<KnowledgeArticleDTO> listBySearch(KnowledgeArticleSrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<KnowledgeArticle> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        Sort sort = searchDTO.getSort();
        List<KnowledgeArticle> result = (sort == null)
                ? query.findAll(specification)
                : query.findAll(specification, sort);
        return result.stream()
                .map(CrmMapper::toDTO)
                .collect(Collectors.toList());
    }

    /**
     * Finds KnowledgeArticle entities matching the search criteria, paged.
     */
    public Page<KnowledgeArticleDTO> findBySearch(KnowledgeArticleSrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<KnowledgeArticle> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        Pageable pageable = searchDTO.getPageable();
        return query.findAll(specification, pageable)
                .map(CrmMapper::toDTO);
    }

    /**
     * Finds the first KnowledgeArticle matching the search criteria, or null.
     */
    public KnowledgeArticleDTO findFirstBySearch(KnowledgeArticleSrchDTO searchDTO) {
        searchDTO.setPageSize(1);
        List<KnowledgeArticleDTO> list = findBySearch(searchDTO).getContent();
        return list.isEmpty() ? null : list.get(0);
    }

    /**
     * Counts KnowledgeArticle entities matching the search criteria.
     */
    public long countBySearch(KnowledgeArticleSrchDTO searchDTO) {
        accessSearch(searchDTO);
        Specification<KnowledgeArticle> specification = ownedOnly(CrmMapper.toSpec(searchDTO));
        return query.count(specification);
    }

    /**
     * Finds a KnowledgeArticle by its identifier.
     */
    public Optional<KnowledgeArticleDTO> findById(Long articleId) {
        return repository.findById(articleId)
                .filter(this::readable)
                .map(e -> CrmMapper.toDTO(e, MappingContext.withGuard(2)));
    }

    /**
     * Saves a new KnowledgeArticle from the given DTO.
     *
     * Creates only. An identifier that is already taken is refused rather
     * than merged over, so a create request can never overwrite a row.
     */
    @Transactional
    public KnowledgeArticleDTO save(KnowledgeArticleDTO dto) {
        BeanValidation.validate(dto);
        accessCreate(dto);
        if (dto.getArticleId() != null && repository.existsById(dto.getArticleId()))
            throw new DuplicateKeyException("KnowledgeArticle " + dto.getArticleId() + " already exists; update it instead");
        KnowledgeArticle entity = CrmMapper.toEntity(dto, entityManager);
        entity.setArticleId(null);
        beforeSave(entity, dto);
        KnowledgeArticle result = repository.save(entity);
        return CrmMapper.toDTO(result);
    }

