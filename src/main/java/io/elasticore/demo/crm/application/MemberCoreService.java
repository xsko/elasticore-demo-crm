    /**
     * Deletes a Member by its identifier.
     */
    @Transactional
    public boolean deleteById(Long memberId) {
        repository.findById(memberId).ifPresent(e -> accessWrite(e, "delete"));
        repository.findById(memberId).ifPresent(repository::delete);
        return !repository.existsById(memberId);
    }

