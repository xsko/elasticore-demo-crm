    private void accessAll(String operation) {
        ACCESS.requireAll(currentUser, operation);
    }

    private void accessSearch(MemberSrchDTO searchDTO) {
        ACCESS.require(currentUser, "read");
    }

    /** A search narrowed to the caller's own rows where read is the owner's: an equality, whatever the field searches by. */
    private Specification<Member> ownedOnly(Specification<Member> spec) {
        Object owner = ACCESS.ownerFilter(currentUser, "read");
        if (owner == null) return spec;
        final Long id = io.elasticore.springboot3.security.AccessPolicy.as(owner, Long.class);
        Specification<Member> mine = (r, q, cb) -> cb.equal(r.get("memberId"), id);
        return spec == null ? mine : spec.and(mine);
    }

    private boolean readable(Member entity) {
        ACCESS.require(currentUser, "read");
        return ACCESS.owns(currentUser, "read", entity.getMemberId());
    }

    private void accessWrite(Member entity, String operation) {
        ACCESS.require(currentUser, operation);
        if (!ACCESS.owns(currentUser, operation, entity.getMemberId()))
            throw new EntityNotFoundException("Member not found");
    }

    private void accessCreate(MemberDTO dto) {
        ACCESS.require(currentUser, "create");
        if (!ACCESS.isAdmin(currentUser) || dto.getRole() == null) dto.setRole(new Member().getRole());
        hashPasswords(dto);
    }

    private void accessUpdate(Member entity, MemberDTO dto) {
        if (entity == null) return;
        accessWrite(entity, "update");
        if (!ACCESS.isAdmin(currentUser)) {
            dto.setRole(entity.getRole());
        }
        hashPasswords(dto);
        if (dto.getPassword() != null) io.elasticore.springboot3.security.PasswordRefreshFilter.written(entity.getMemberId(), dto.getPassword());
    }

    private void accessUpdateAll(MemberDTO dto) {
        accessAll("update");
        if (!ACCESS.isAdmin(currentUser)) {
            dto.setRole(null);
        }
        hashPasswords(dto);
    }

    /** A password a request carries is kept only as its hash. */
    private void hashPasswords(MemberDTO dto) {
        if (dto.getPassword() != null) dto.setPassword(passwordHasher.hash(dto.getPassword()));
    }

    /** The Member this login and password belong to, or empty. */
    public Optional<MemberDTO> authenticate(String login, String password) {
        if (login == null || password == null) return Optional.empty();
        List<Member> found = query.findAll((Specification<Member>) (r, q, cb) -> cb.equal(r.get("login"), login));
        if (found.size() != 1) {
            passwordHasher.hash(password);
            return Optional.empty();
        }
        if (!passwordHasher.matches(password, found.get(0).getPassword())) return Optional.empty();
        return Optional.of(CrmMapper.toDTO(found.get(0)));
    }

    /** The Member signed in now - the row the session's identity names - or empty for a visitor. */
