    /**
     * Saves a new Member from the given DTO.
     *
     * Creates only. An identifier that is already taken is refused rather
     * than merged over, so a create request can never overwrite a row.
     */
    @Transactional
    public MemberDTO save(MemberDTO dto) {
        BeanValidation.validate(dto);
        accessCreate(dto);
        if (dto.getMemberId() != null && repository.existsById(dto.getMemberId()))
            throw new DuplicateKeyException("Member " + dto.getMemberId() + " already exists; update it instead");
        Member entity = CrmMapper.toEntity(dto, entityManager);
        entity.setMemberId(null);
        beforeSave(entity, dto);
        Member result = repository.save(entity);
        return CrmMapper.toDTO(result);
    }

