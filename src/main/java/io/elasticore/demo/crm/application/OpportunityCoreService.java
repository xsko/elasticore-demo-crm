    /**
     * Applies the non-null fields of the DTO to every Opportunity the
     * Specification matches. Requires at least one condition so a whole
     * table can never be updated by accident.
     *
     * Each row is loaded and changed through the mapper rather than by a bulk
     * UPDATE, so the version, the audit trail and every rule the entity
     * checks on write still apply to it.
     */
    @Transactional
    public int updateBySpecification(OpportunityDTO dto, Specification<Opportunity> spec) {
        EntityManager em = entityManager;
        CriteriaBuilder cb = em.getCriteriaBuilder();
        CriteriaQuery<Opportunity> probe = cb.createQuery(Opportunity.class);
        Predicate predicate = spec == null ? null : spec.toPredicate(probe.from(Opportunity.class), probe, cb);
        if (predicate == null)
            throw new IllegalArgumentException("Update condition is missing. Full table update is not allowed.");
        if (dto.getOpportunityId() != null)
            throw new IllegalArgumentException("An update by condition cannot change an identifier; use update(dto) for one row.");
        BeanValidation.validatePresent(dto);
        accessUpdateAll(dto);

        List<Opportunity> targets = query.findAll(spec);
        for (Opportunity entity : targets) {
            CrmMapper.mapping(dto, entity, true, em);
            entity.requireReferences(entityManager::find);
            beforeSave(entity, dto);
            repository.save(entity);
        }
        return targets.size();
    }

