    /**
     * Saves a new Opportunity from the given DTO.
     *
     * Creates only. An identifier that is already taken is refused rather
     * than merged over, so a create request can never overwrite a row.
     */
    @Transactional
    public OpportunityDTO save(OpportunityDTO dto) {
        BeanValidation.validate(dto);
        accessCreate(dto);
        if (dto.getOpportunityId() != null && repository.existsById(dto.getOpportunityId()))
            throw new DuplicateKeyException("Opportunity " + dto.getOpportunityId() + " already exists; update it instead");
        Opportunity entity = CrmMapper.toEntity(dto, entityManager);
        entity.setOpportunityId(null);
        entity.requireReferences(entityManager::find);
        beforeSave(entity, dto);
        Opportunity result = readBack(repository.save(entity));
        return CrmMapper.toDTO(result);
    }

