    protected void beforeSave(Product entity) {
    }

    /**
     * The same moment, with the request that wrote it - for what the entity
     * cannot tell by itself: whether this request carried a value, which a
     * password to be hashed needs to know on every one of the four paths.
     *
     * Calls beforeSave(entity) here; override either one.
     */
    protected void beforeSave(Product entity, ProductDTO request) {
        beforeSave(entity);
    }

    /**
     * Updates an existing Product from the given DTO.
     */
    @Transactional
    public ProductDTO update(ProductDTO dto) {
        BeanValidation.validatePresent(dto);
        Product entity = repository.findById(dto.getProductId()).orElse(null);
        accessUpdate(entity, dto);
        if (entity == null)
            throw new EntityNotFoundException("Invalid ProductDTO ID");
        CrmMapper.mapping(dto, entity, true, entityManager);
        beforeSave(entity, dto);
        return CrmMapper.toDTO(repository.save(entity));
    }

    /**
     * Updates multiple Product entities in one transaction, each
     * through update(dto) - so an override of update() in the extension
     * service governs PUT /batch too.
     */
    @Transactional
    public void batchUpdate(List<ProductDTO> dtoList) {
        if (dtoList == null || dtoList.isEmpty()) {
            return;
        }
        for (ProductDTO dto : dtoList) {
            update(dto);
        }
    }

    /**
     * Deletes Product entities by their key DTOs.
     */
    @Transactional
    public List<Boolean> delete(List<ProductKeyDTO> dtoList) {
        List<Boolean> result = new ArrayList<>();
        for (ProductKeyDTO dto : dtoList) {
            result.add(this.deleteById(dto.getProductId()));
        }
        return result;
    }

    /**
     * Deletes a Product by its identifier.
     */
    @Transactional
    public boolean deleteById(Long productId) {
        repository.findById(productId).ifPresent(e -> accessWrite(e, "delete"));
        repository.findById(productId).ifPresent(repository::delete);
        return !repository.existsById(productId);
    }

    /**
     * Updates Product entities matching the search criteria,
     * using non-null fields from the update DTO.
     */
    @Transactional
    public int updateBySpecification(ProductDTO dto, ProductSrchDTO srchDTO) {
        return updateBySpecification(dto, CrmMapper.toSpec(srchDTO));
    }

    /**
     * Applies the non-null fields of the DTO to every Product the
     * Specification matches. Requires at least one condition so a whole
     * table can never be updated by accident.
     *
     * Each row is loaded and changed through the mapper rather than by a bulk
     * UPDATE, so the version, the audit trail and every rule the entity
     * checks on write still apply to it.
     */
    @Transactional
    public int updateBySpecification(ProductDTO dto, Specification<Product> spec) {
        EntityManager em = entityManager;
        CriteriaBuilder cb = em.getCriteriaBuilder();
        CriteriaQuery<Product> probe = cb.createQuery(Product.class);
        Predicate predicate = spec == null ? null : spec.toPredicate(probe.from(Product.class), probe, cb);
        if (predicate == null)
            throw new IllegalArgumentException("Update condition is missing. Full table update is not allowed.");
        if (dto.getProductId() != null)
            throw new IllegalArgumentException("An update by condition cannot change an identifier; use update(dto) for one row.");
        BeanValidation.validatePresent(dto);
        accessUpdateAll(dto);

        List<Product> targets = query.findAll(spec);
        for (Product entity : targets) {
            CrmMapper.mapping(dto, entity, true, em);
            beforeSave(entity, dto);
            repository.save(entity);
        }
        return targets.size();
    }

