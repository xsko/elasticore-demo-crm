    private void accessAll(String operation) {
        ACCESS.requireAll(currentUser, operation);
    }

    private void accessSearch(ProductSrchDTO searchDTO) {
        ACCESS.require(currentUser, "read");
    }

    /** A search narrowed to the caller's own rows where read is the owner's: an equality, whatever the field searches by. */
    private Specification<Product> ownedOnly(Specification<Product> spec) {
        Object owner = ACCESS.ownerFilter(currentUser, "read");
        if (owner == null) return spec;
        throw new io.elasticore.springboot3.security.ForbiddenException("Product is read by its owner, and names none (@owner)");
    }

    private boolean readable(Product entity) {
        ACCESS.require(currentUser, "read");
        return ACCESS.owns(currentUser, "read", null);
    }

    private void accessWrite(Product entity, String operation) {
        ACCESS.require(currentUser, operation);
        if (!ACCESS.owns(currentUser, operation, null))
            throw new EntityNotFoundException("Product not found");
    }

    private void accessCreate(ProductDTO dto) {
        ACCESS.require(currentUser, "create");
        hashPasswords(dto);
    }

    private void accessUpdate(Product entity, ProductDTO dto) {
        if (entity == null) return;
        accessWrite(entity, "update");
        hashPasswords(dto);
    }

    private void accessUpdateAll(ProductDTO dto) {
        accessAll("update");
        hashPasswords(dto);
    }

