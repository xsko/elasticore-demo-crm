    /**
     * Saves a new Ticket from the given DTO.
     *
     * Creates only. An identifier that is already taken is refused rather
     * than merged over, so a create request can never overwrite a row.
     */
    @Transactional
    public TicketDTO save(TicketDTO dto) {
        BeanValidation.validate(dto);
        accessCreate(dto);
        if (dto.getTicketId() != null && repository.existsById(dto.getTicketId()))
            throw new DuplicateKeyException("Ticket " + dto.getTicketId() + " already exists; update it instead");
        Ticket entity = CrmMapper.toEntity(dto, entityManager);
        entity.setTicketId(null);
        entity.requireReferences(entityManager::find);
        beforeSave(entity, dto);
        Ticket result = readBack(repository.save(entity));
        return CrmMapper.toDTO(result);
    }

