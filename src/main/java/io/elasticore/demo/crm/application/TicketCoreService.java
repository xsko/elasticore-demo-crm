    /**
     * Deletes a Ticket by its identifier.
     */
    @Transactional
    public boolean deleteById(Long ticketId) {
        repository.findById(ticketId).ifPresent(e -> accessWrite(e, "delete"));
        repository.findById(ticketId).ifPresent(repository::delete);
        return !repository.existsById(ticketId);
    }

